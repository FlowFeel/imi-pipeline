"""Static assertions against the Observatory V2 prod compose config.

These tests verify the generated ``compose.prod.yml`` without running
Docker. They catch the class of issues that bit us on 2026-07-23:

- Volume mounted at wrong path (images at /mediawiki/images instead of
  /var/www/mediawiki/w/images)
- Wrong MySQL version (8.0 vs 8.4.0 — incompatible InnoDB format)
- Wrong DB server name (db vs observatorywiki-db)
- Wrong image registry (janfrel vs flowfeel)
- Missing external volume references

These are pure YAML assertions — no network, no containers, <0.1s.

The compose file is generated by ``docker/generate_compose.py prod``
from the ``docker/docker-compose.j2`` template. If the template or
generator is wrong, these tests fail before the code reaches Hetzner.

Usage:
    pytest lib/python/imi/tests/test_observatory_compose.py -v
"""

from __future__ import annotations

from pathlib import Path

import pytest

try:
    import yaml
except ImportError:
    yaml = None

# Path to the Observatory V2 repo on the workspace
# When running locally (Hetzner), this is the deployed compose file.
# When running in CI, the repo is checked out at workspace root.
REPO_PATH = (
    Path(__file__).parent.parent.parent.parent.parent / "observatory-magazine-v2"
)
COMPOSE_PATH = REPO_PATH / "compose.prod.yml"


def load_compose() -> dict:
    """Load and parse the Observatory V2 prod compose YAML."""
    if yaml is None:
        pytest.skip("pyyaml not installed")
    if not COMPOSE_PATH.exists():
        pytest.skip(f"Compose file not found: {COMPOSE_PATH}")
    with open(COMPOSE_PATH) as f:
        return yaml.safe_load(f)


@pytest.fixture(scope="module")
def compose():
    return load_compose()


@pytest.fixture(scope="module")
def web_service(compose):
    services = compose.get("services", {})
    return services.get("web", {})


@pytest.fixture(scope="module")
def db_service(compose):
    services = compose.get("services", {})
    # The db service is named with the project prefix
    for name, svc in services.items():
        if "db" in name and "mysql" in svc.get("image", ""):
            return svc
    return services.get("observatorywiki-db", {})


class TestImageConfig:
    """Assert the web service uses the correct image."""

    def test_image_uses_flowfeel_registry(self, web_service) -> None:
        """Image must be from ghcr.io/flowfeel, not janfrel or phosphene."""
        image = web_service.get("image", "")
        assert "ghcr.io/flowfeel/observatory-mediawiki" in image, (
            f"Image should be ghcr.io/flowfeel/observatory-mediawiki, got: {image}"
        )

    def test_image_has_explicit_tag(self, web_service) -> None:
        """Image must have an explicit version tag, not :latest."""
        image = web_service.get("image", "")
        tag = image.split(":")[-1] if ":" in image else ""
        assert tag and tag != "latest", (
            f"Image must have explicit tag (not :latest), got: {image}"
        )


class TestMySQLConfig:
    """Assert MySQL version and DB server configuration."""

    def test_mysql_version_is_8_4(self, db_service) -> None:
        """MySQL must be 8.4.0 — V1 data is 8.4, cannot downgrade to 8.0."""
        image = db_service.get("image", "")
        assert "mysql:8.4" in image, (
            f"MySQL must be 8.4.x (V1 data is 8.4, cannot downgrade). Got: {image}"
        )

    def test_db_server_is_observatorywiki_db(self, web_service) -> None:
        """MW_DB_SERVER must be observatorywiki-db, not 'db'.

        V1's compose had a service named 'db' which provided the DNS alias.
        V2's compose names it 'observatorywiki-db'. If MW_DB_SERVER is still
        'db', the web container cannot connect after V1 is stopped.
        """
        env = web_service.get("environment", {})
        db_server = env.get("MW_DB_SERVER", "")
        assert db_server == "observatorywiki-db", (
            f"MW_DB_SERVER must be 'observatorywiki-db' (not 'db'). Got: {db_server}"
        )


class TestVolumeMounts:
    """Assert volumes mount at the correct paths.

    The V2 image (ghcr.io/flowfeel/observatory-mediawiki) does not create
    the Taqasta symlink from /var/www/mediawiki/w/images → /mediawiki/images.
    The images volume must mount directly at the MW web path.
    """

    def test_images_volume_mounts_at_mw_web_path(self, web_service) -> None:
        """Images volume must mount at /var/www/mediawiki/w/images.

        If it mounts at /mediawiki/images, author headshots and article
        thumbnails return 404 because Apache can't find the files.
        """
        volumes = web_service.get("volumes", [])
        image_mounts = [v for v in volumes if "mediawiki-images" in str(v)]
        assert image_mounts, "No mediawiki-images volume mount found"

        for mount in image_mounts:
            parts = str(mount).split(":")
            if len(parts) >= 2 and "mediawiki-images" in parts[0]:
                mount_path = parts[1]
                assert mount_path == "/var/www/mediawiki/w/images", (
                    f"Images volume must mount at /var/www/mediawiki/w/images, "
                    f"got: {mount_path}"
                )

    def test_db_data_volume_mounts_at_var_lib_mysql(self, db_service) -> None:
        """DB data volume must mount at /var/lib/mysql."""
        volumes = db_service.get("volumes", [])
        db_mounts = [v for v in volumes if "db-data" in str(v)]
        assert db_mounts, "No db-data volume mount found"

        for mount in db_mounts:
            parts = str(mount).split(":")
            if len(parts) >= 2 and "db-data" in parts[0]:
                mount_path = parts[1]
                assert mount_path == "/var/lib/mysql", (
                    f"DB data volume must mount at /var/lib/mysql, got: {mount_path}"
                )


class TestExternalVolumes:
    """Assert prod uses external volumes pointing at V1's data."""

    def test_volumes_are_external(self, compose) -> None:
        """Prod volumes must be external — referencing V1's existing data."""
        volumes = compose.get("volumes", {})
        for name, config in volumes.items():
            if config is None:
                continue
            if name == "varnish-data":
                continue  # varnish-data is not external (ephemeral)
            assert config.get("external") is True, (
                f"Volume '{name}' must be external in prod. Got: {config}"
            )

    def test_db_data_volume_name_is_observatorywiki_db_data(self, compose) -> None:
        """DB data volume must reference observatorywiki_db_data (underscore).

        Not observatorywiki_db-data (dash) — that's a different volume that
        was created by Docker's default naming and doesn't have V1's data.
        """
        volumes = compose.get("volumes", {})
        db_vol = volumes.get("db-data", {})
        name = db_vol.get("name", "")
        assert name == "observatorywiki_db_data", (
            f"DB volume name must be 'observatorywiki_db_data' (underscore), "
            f"not 'observatorywiki_db-data' (dash). Got: {name}"
        )

    def test_images_volume_name_is_observatorywiki_images(self, compose) -> None:
        """Images volume must reference observatorywiki_images.

        Not observatorywiki_mediawiki-images — that's a different volume
        that only has README and .htaccess, not the actual image files.
        """
        volumes = compose.get("volumes", {})
        img_vol = volumes.get("mediawiki-images", {})
        name = img_vol.get("name", "")
        assert name == "observatorywiki_images", (
            f"Images volume name must be 'observatorywiki_images', "
            f"not 'observatorywiki_mediawiki-images'. Got: {name}"
        )


class TestNetworkConfig:
    """Assert network configuration matches production."""

    def test_uses_external_network(self, compose) -> None:
        """Prod must use the external observatorywiki_default network."""
        networks = compose.get("networks", {})
        for name, config in networks.items():
            if config is None:
                continue
            if name == "traefik-public":
                assert config.get("external") is True, (
                    f"Network '{name}' must be external in prod"
                )
            elif "observatorywiki" in name or "net" in name:
                assert config.get("external") is True, (
                    f"Network '{name}' must be external in prod. Got: {config}"
                )
